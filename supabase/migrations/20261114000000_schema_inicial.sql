-- =====================================================================
-- Gravoris — schema inicial no Supabase (PostgreSQL)
-- Execute no Supabase: SQL Editor > New query > cole este arquivo > Run
-- (ou: supabase db push, se usar a Supabase CLI).
-- O script pode ser executado mais de uma vez sem duplicar nada.
--
-- Arquitetura: o frontend NÃO acessa o banco diretamente. Toda leitura e
-- escrita passa pelo backend Spring Boot, que valida autenticação e papéis.
-- Por isso o RLS fica ATIVO e SEM políticas para os papéis anon/authenticated:
-- a Data API pública do Supabase não consegue ler nem alterar nada, mesmo
-- que a anon key vaze. O backend conecta como o usuário "postgres"
-- (dono das tabelas), que não é afetado pelo RLS.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- Usuários (clientes e administradores)
-- ---------------------------------------------------------------------
create table if not exists public.clientes (
    id              bigint generated by default as identity primary key,
    nome            varchar(255) not null,
    email           varchar(255) not null,
    senha           varchar(255) not null,          -- hash BCrypt, nunca texto puro
    telefone        varchar(255),
    cpf             varchar(255) not null,
    data_nascimento date,
    ativo           boolean      not null default true,
    role            varchar(20)  not null default 'CLIENTE',
    criado_em       timestamp(6) not null default now(),
    constraint uk_clientes_email unique (email),
    constraint uk_clientes_cpf unique (cpf),
    constraint ck_clientes_role check (role in ('CLIENTE', 'ADMINISTRADOR')),
    constraint ck_clientes_cpf check (cpf ~ '^[0-9]{11}$')
);

-- E-mail único sem diferenciar maiúsculas/minúsculas
create unique index if not exists ux_clientes_email_lower on public.clientes (lower(email));
create index if not exists ix_clientes_role on public.clientes (role);

-- ---------------------------------------------------------------------
-- Veículos / anúncios
-- ---------------------------------------------------------------------
create table if not exists public.produtos (
    id             bigint generated by default as identity primary key,
    nome           varchar(255)   not null,
    marca          varchar(255)   not null,
    modelo         varchar(255)   not null,
    preco          numeric(38, 2) not null,
    descricao      text,
    imagem_url     varchar(1000),
    ano            integer        not null default 0,
    quilometragem  integer        not null default 0,
    categoria      varchar(255),
    estoque        integer        not null default 0,
    motor          varchar(255),
    potencia       integer        not null default 0,
    torque         varchar(255),
    velocidade_max integer        not null default 0,
    aceleracao     varchar(255),
    -- ativo = aparece na vitrine; sempre igual a (status = 'APROVADO'), mantido pelo backend
    ativo          boolean        not null default true,
    status         varchar(20)    not null default 'APROVADO',
    criado_em      timestamp(6)   not null default now(),
    atualizado_em  timestamp(6)   not null default now(),
    constraint ck_produtos_preco check (preco > 0),
    constraint ck_produtos_estoque check (estoque >= 0),
    constraint ck_produtos_quilometragem check (quilometragem >= 0),
    constraint ck_produtos_categoria check (categoria in ('SEDAN', 'SUV', 'ESPORTIVO', 'PICKUP', 'HATCH')),
    constraint ck_produtos_status check (status in ('PENDENTE', 'APROVADO', 'DESATIVADO')),
    constraint ck_produtos_ativo_status check (ativo = (status = 'APROVADO'))
);

create index if not exists ix_produtos_ativo on public.produtos (ativo);
create index if not exists ix_produtos_status on public.produtos (status);
create index if not exists ix_produtos_marca on public.produtos (lower(marca));

-- ---------------------------------------------------------------------
-- Pedidos
-- ---------------------------------------------------------------------
create table if not exists public.pedidos (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint         not null,
    data_pedido timestamp(6)   not null default now(),
    total       numeric(38, 2) not null,
    status      varchar(255)   not null default 'PENDENTE',
    -- RESTRICT: um cliente com pedidos não pode ser apagado (o histórico é preservado)
    constraint fk_pedidos_cliente foreign key (cliente_id)
        references public.clientes (id) on update cascade on delete restrict,
    constraint ck_pedidos_total check (total >= 0),
    constraint ck_pedidos_status check (status in ('PENDENTE', 'CONFIRMADO', 'ENTREGUE', 'CANCELADO'))
);

create index if not exists ix_pedidos_cliente on public.pedidos (cliente_id);
create index if not exists ix_pedidos_data on public.pedidos (data_pedido desc);

-- ---------------------------------------------------------------------
-- Itens do pedido
-- ---------------------------------------------------------------------
create table if not exists public.item_pedido (
    id              bigint generated by default as identity primary key,
    pedido_id       bigint         not null,
    produto_id      bigint         not null,
    quantidade      integer        not null,
    preco_unitario  numeric(38, 2) not null,
    -- CASCADE: itens pertencem ao pedido; RESTRICT: veículo vendido não pode ser apagado
    constraint fk_item_pedido_pedido foreign key (pedido_id)
        references public.pedidos (id) on update cascade on delete cascade,
    constraint fk_item_pedido_produto foreign key (produto_id)
        references public.produtos (id) on update cascade on delete restrict,
    constraint ck_item_pedido_quantidade check (quantidade > 0),
    constraint ck_item_pedido_preco check (preco_unitario >= 0)
);

create index if not exists ix_item_pedido_pedido on public.item_pedido (pedido_id);
create index if not exists ix_item_pedido_produto on public.item_pedido (produto_id);

-- ---------------------------------------------------------------------
-- Segurança: RLS ativo e nenhum acesso pela Data API pública
-- ---------------------------------------------------------------------
alter table public.clientes    enable row level security;
alter table public.produtos    enable row level security;
alter table public.pedidos     enable row level security;
alter table public.item_pedido enable row level security;

revoke all on table public.clientes, public.produtos, public.pedidos, public.item_pedido from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

-- ---------------------------------------------------------------------
-- Supabase Storage: bucket das imagens dos anúncios
-- Leitura pública (as fotos aparecem no site); envio só pelo backend com a
-- service_role key, então nenhuma política de escrita é criada para anon/authenticated.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('veiculos', 'veiculos', true, 5242880,
        array['image/jpeg', 'image/png', 'image/webp', 'image/avif'])
on conflict (id) do update
    set public = excluded.public,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;

commit;
